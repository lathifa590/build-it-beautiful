// Shared JSON Sanitization & Truncation-Repair Parser for Edge Functions
// ============================================================

export const sanitizeJsonResponse = (text: string): string => {
  let cleaned = text.trim();
  if (cleaned.startsWith("```json")) {
    cleaned = cleaned.slice(7);
  } else if (cleaned.startsWith("```")) {
    cleaned = cleaned.slice(3);
  }
  if (cleaned.endsWith("```")) {
    cleaned = cleaned.slice(0, -3);
  }
  cleaned = cleaned.trim();

  // 1. Escape LaTeX commands starting with u that are NOT valid 4-hex JSON unicode escapes (\underline, \upsilon, \uparrow)
  cleaned = cleaned.replace(/(?<!\\)\\(?=u(?![0-9a-fA-F]{4}))/g, "\\\\");

  // 2. Escape LaTeX commands starting with b, f, r, t followed by letters (\tfrac, \tanh, \boldsymbol, \frac, etc.)
  // Di JSON, \b, \f, \r, \t tidak pernah diikuti langsung oleh huruf kata.
  cleaned = cleaned.replace(/(?<!\\)\\(?=[bfrt][a-zA-Z])/g, "\\\\");

  // 3. Escape LaTeX commands starting with n (\nabla, \neq, \notin, \nu, \neg, \natural, \newline, \nonumber, \norm, \not)
  cleaned = cleaned.replace(
    /(?<!\\)\\(?=(?:nabla|neq|notin|nu|neg|natural|newline|nonumber|norm|not\b|ne\b))/g,
    "\\\\"
  );

  // 4. Fix illegal backslash escapes (e.g. \pi, \sqrt, \alpha from LaTeX)
  cleaned = cleaned.replace(/(?<!\\)\\(?!["\\/bfnrtu])/g, "\\\\");

  // Replace literal control characters inside raw string
  cleaned = cleaned.replace(/[\n\r\t]+/g, " ");

  return cleaned;
};

export const extractJsonFromResponse = (text: string): string => {
  const cleaned = sanitizeJsonResponse(text);

  const objectStart = cleaned.indexOf("{");
  const arrayStart = cleaned.indexOf("[");
  const starts = [objectStart, arrayStart].filter((idx) => idx >= 0);
  const start = starts.length ? Math.min(...starts) : -1;

  if (start >= 0) {
    const isObject = cleaned[start] === "{";
    const end = isObject ? cleaned.lastIndexOf("}") : cleaned.lastIndexOf("]");

    if (end > start) {
      return cleaned.substring(start, end + 1);
    }
  }

  return cleaned;
};

export const parseGeneratedJson = (
  text: string
): { parsed?: any; sanitized: string; error?: unknown } => {
  const sanitized = extractJsonFromResponse(text);
  try {
    return { parsed: JSON.parse(sanitized), sanitized };
  } catch (parseError) {
    try {
      const fallbackContent = sanitizeJsonResponse(text);
      return { parsed: JSON.parse(fallbackContent), sanitized: fallbackContent };
    } catch {
      try {
        let repaired = sanitizeJsonResponse(text);
        const objStart = repaired.indexOf("{");
        const arrStart = repaired.indexOf("[");
        const starts = [objStart, arrStart].filter((idx) => idx >= 0);
        if (starts.length > 0) {
          repaired = repaired.substring(Math.min(...starts));
        }

        // Remove ellipsis frequently generated by LLMs
        repaired = repaired.replace(/,\s*\.\.\./g, "");
        repaired = repaired.replace(/\.\.\.\s*,/g, "");
        repaired = repaired.replace(/\[\s*\.\.\.\s*\]/g, "[]");
        repaired = repaired.replace(/\{\s*\.\.\.\s*\}/g, "{}");
        repaired = repaired.replace(/([^"\w])\.\.\.(?=[^"\w]|$)/g, "$1null");

        // Strip trailing incomplete key/value or dangling comma at the end of truncated stream
        repaired = repaired.replace(/,\s*"[^"]*$/, "");
        repaired = repaired.replace(/:\s*"[^"]*$/, ': ""');
        repaired = repaired.replace(/,\s*$/, "");

        // Tutup delimiter yang belum tertutup dengan stack LIFO (agar urutan objek & array tepat)
        const stack: string[] = [];
        let inString = false;
        let isEscaped = false;

        for (let i = 0; i < repaired.length; i++) {
          const char = repaired[i];
          if (isEscaped) {
            isEscaped = false;
            continue;
          }
          if (char === "\\") {
            isEscaped = true;
            continue;
          }
          if (char === '"') {
            inString = !inString;
            continue;
          }
          if (!inString) {
            if (char === "{") stack.push("}");
            else if (char === "[") stack.push("]");
            else if (char === "}" || char === "]") {
              if (stack.length > 0 && stack[stack.length - 1] === char) {
                stack.pop();
              }
            }
          }
        }

        if (inString) {
          repaired += '"';
        }

        while (stack.length > 0) {
          repaired += stack.pop();
        }

        return { parsed: JSON.parse(repaired), sanitized: repaired };
      } catch (repairError) {
        try {
          const cpMatch = text.match(
            /["']?cp_kontekstual["']?\s*:\s*["']([^"']*(?:\\.[^"']*)*)["']?/
          );
          if (cpMatch?.[1]) {
            return { parsed: { cp_kontekstual: cpMatch[1].trim() }, sanitized: text };
          }
        } catch {
          /* ignore */
        }
        return { sanitized, error: repairError || parseError };
      }
    }
  }
};
